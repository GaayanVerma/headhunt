// Minimal **bold**-only inline renderer - the assistant's replies use basic
// markdown emphasis, and a literal "**word**" reads as broken. Not pulling
// in a full markdown library for one pattern.
export function ChatText({ text }: { text: string }) {
  const parts = text.split(/(\*\*[^*]+\*\*)/g);
  return (
    <>
      {parts.map((part, i) =>
        part.startsWith("**") && part.endsWith("**") ? (
          <strong key={i}>{part.slice(2, -2)}</strong>
        ) : (
          <span key={i}>{part}</span>
        )
      )}
    </>
  );
}
